  await shot('inspection-back');
  await page.locator('[data-journal-reset]').click();
  assert.equal(await canvas.getAttribute('data-journal-yaw'),'0');
  await page.mouse.click(450,400);await phase('reading');
  await shot('inspection-reading');
  assert.equal(await page.locator('[data-journal-progress]').textContent(),'1–2 / '+count);
  await drag(550,400,340,300);
  assert.ok(Math.abs(Number(await canvas.getAttribute('data-journal-yaw')))<=25*Math.PI/180);
  assert.ok(Math.abs(Number(await canvas.getAttribute('data-journal-pitch')))<=15*Math.PI/180);
  assert.equal(await canvas.getAttribute('data-journal-page'),'0','body drag must not turn a page');
  await page.locator('[data-journal-reset]').click();
  await page.getByRole('button',{name:'拉近书本',exact:true}).click();
  assert.equal(await canvas.getAttribute('data-journal-zoom'),'1.25');
  assert.equal(await page.locator('[data-journal-image]').isVisible(),false);
  await drag(550,400,50,20);assert.notEqual(await canvas.getAttribute('data-journal-pan'),'0,0');await page.locator('[data-journal-reset]').click();
  assert.equal(await canvas.getAttribute('data-journal-pan'),'0,0');
  await page.mouse.move(450,400);await page.mouse.wheel(0,-200);
  await page.waitForFunction(()=>Number(document.querySelector('canvas[data-journal-zoom]').dataset.journalZoom)>1);
  await page.locator('[data-journal-reset]').click();
  await page.locator('[data-journal-mode]').click();
  assert.match(await page.locator('[data-journal-text]').textContent(),/生活节奏/);
  await page.keyboard.press('Escape');assert.equal(await page.locator('[data-journal-text]').isVisible(),false);
  assert.equal(await page.locator('[data-journal-directory]').count(),0);
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('[data-journal-progress]').textContent.startsWith('1 /'));
  await shot('inspection-mobile');
