  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:160,y:350,id:1},{x:220,y:380,id:2}]});
  await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:110,y:340,id:1},{x:280,y:390,id:2}]});
  await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await page.waitForFunction(()=>Number(document.querySelector('canvas[data-journal-zoom]').dataset.journalZoom)>1);
  await page.locator('[data-journal-reset]').click();await touch.detach();
